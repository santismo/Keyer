#!/usr/bin/env node
'use strict';

/*
 * Build the static catalog consumed by Keyer's Tab files bank.
 *
 * A static site cannot safely enumerate a deployed directory. Run this after
 * adding/removing files under tab-library/inbox so the browser gets a compact,
 * searchable manifest without uploading users' personal files anywhere else.
 */

const fs = require('node:fs');
const path = require('node:path');
const TabImport = require('../tab-import.js');

const root = path.resolve(__dirname, '..');
const inputDirectory = path.resolve(process.argv[2] || path.join(root, 'tab-library', 'inbox'));
const outputPath = path.resolve(process.argv[3] || path.join(root, 'tab-library-catalog.js'));
const supportedExtensions = new Set([...TabImport.directExtensions, ...TabImport.conversionExtensions]);

function filesUnder(directory) {
  if (!fs.existsSync(directory)) return [];
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(item => {
    const target = path.join(directory, item.name);
    if (item.isDirectory()) return filesUnder(target);
    if (!item.isFile() || item.name.startsWith('.')) return [];
    return [target];
  });
}

function toWebPath(relative) {
  return ['tab-library', 'inbox'].concat(relative.split(path.sep)).map(encodeURIComponent).join('/');
}

function sourceEntry(file) {
  const relative = path.relative(inputDirectory, file);
  const extension = TabImport.extensionOf(file);
  const direct = TabImport.isDirectlySupported(file);
  const entry = {
    file: relative,
    url: toWebPath(relative),
    extension,
    direct,
    title: TabImport.titleFromFileName(relative),
    artist: '',
    bpm: 0,
    tracks: []
  };
  if (!direct) return entry;
  try {
    const parsed = TabImport.parseScore(fs.readFileSync(file), relative);
    entry.title = parsed.title;
    entry.artist = parsed.artist;
    entry.bpm = parsed.bpm;
    entry.tracks = parsed.tracks.map(track => ({ index: track.index, name: track.name, fretted: track.fretted, stringCount: track.stringCount }));
  } catch (error) {
    entry.direct = false;
    entry.error = error.message || 'Could not read this tab.';
  }
  return entry;
}

function writeCatalog(entries) {
  const directCount = entries.filter(entry => entry.direct).length;
  const conversionCount = entries.filter(entry => !entry.direct).length;
  const generated = {
    entries,
    directCount,
    conversionCount,
    sourceDirectory: 'tab-library/inbox'
  };
  const source = `/* Generated by scripts/build-tab-library-catalog.js. */\n(function attachKeyerTabLibraryCatalog(root, factory) {\n  var api = factory();\n  if (typeof module === 'object' && module.exports) module.exports = api;\n  if (root) root.KeyerTabLibraryCatalog = api;\n})(typeof globalThis !== 'undefined' ? globalThis : this, function buildKeyerTabLibraryCatalog() {\n  'use strict';\n  return Object.freeze(${JSON.stringify(generated, null, 2)});\n});\n`;
  fs.writeFileSync(outputPath, source);
}

const entries = filesUnder(inputDirectory)
  .filter(file => supportedExtensions.has(TabImport.extensionOf(file)))
  .map(sourceEntry)
  .sort((left, right) => left.title.localeCompare(right.title, undefined, { sensitivity: 'base' }) || left.file.localeCompare(right.file));
writeCatalog(entries);
console.log(`Wrote ${entries.length} tab entries (${entries.filter(entry => entry.direct).length} direct, ${entries.filter(entry => !entry.direct).length} conversion needed) to ${path.relative(root, outputPath)}.`);
