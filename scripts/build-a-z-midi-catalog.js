#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const Midi = require('../miditar-midi.js');
const Theory = require('../jazz-theory.js');

const root = path.resolve(__dirname, '..');
const sourceDirectory = path.resolve(process.argv[2] || path.join(root, 'a-z-midi'));
const outputPath = path.resolve(process.argv[3] || path.join(root, 'a-z-midi-catalog.js'));

if (!fs.existsSync(sourceDirectory)) {
  throw new Error(`A-Z MIDI directory not found: ${sourceDirectory}`);
}

const entries = fs.readdirSync(sourceDirectory)
  .filter(file => /\.midi?$/i.test(file))
  .sort((left, right) => left.localeCompare(right, undefined, { sensitivity: 'base', numeric: true }))
  .map(file => {
    const filePath = path.join(sourceDirectory, file);
    const payload = fs.readFileSync(filePath);
    const midi = Midi.parseMidi(payload, file);
    const melodyTrack = Midi.chooseMelodyTrack(midi);
    const chordMarkers = midi.markers.filter(marker => (
      marker.type === 'marker' && Boolean(Theory.parseChordSymbol(marker.text))
    ));
    return {
      file,
      title: midi.title || file.replace(/\.midi?$/i, ''),
      bpm: Math.round(Number(midi.tempos?.[0]?.bpm) || 120),
      durationSeconds: Math.round(Number(midi.duration) || 0),
      chordMarkers: chordMarkers.length,
      melodyNotes: melodyTrack?.notes?.length || 0,
      bytes: payload.byteLength,
      playable: Boolean(chordMarkers.length && melodyTrack?.notes?.length)
    };
  });

const source = `/* Generated by scripts/build-a-z-midi-catalog.js. */
(function attachKeyerAzMidiCatalog(root, factory) {
  var api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  if (root) root.KeyerAzMidiCatalog = api;
})(typeof globalThis !== 'undefined' ? globalThis : this, function buildKeyerAzMidiCatalog() {
  'use strict';
  var entries = ${JSON.stringify(entries, null, 2)};
  entries.forEach(function freezeEntry(entry) { Object.freeze(entry); });
  return Object.freeze({
    entries: Object.freeze(entries),
    playableEntries: Object.freeze(entries.filter(function playable(entry) { return entry.playable; })),
    fileCount: entries.length,
    playableCount: entries.filter(function playable(entry) { return entry.playable; }).length
  });
});
`;

fs.writeFileSync(outputPath, source);
console.log(`Wrote ${entries.length} entries to ${path.relative(root, outputPath)}.`);
